    private void voltaPerfilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_voltaPerfilActionPerformed
        int userId = UsuarioSession.getUserId();
        System.out.println("userId: " + userId);  // Verifique o valor de userId antes de buscar no banco
        InfoAcesso infoAcesso = new InfoAcesso();
        UsuarioInfo usuarioInfo = infoAcesso.getUsuarioInfo(userId);

        System.out.println("usuarioInfo: " + usuarioInfo);  // Para verificar se está null

        if (usuarioInfo != null) {
            perfil = new TelaPerfil(usuarioInfo);  // Agora, usuarioInfo não é null
            perfil.setExtendedState(perfil.MAXIMIZED_BOTH);
            perfil.setLocationRelativeTo(null);
            perfil.setVisible(true);
            this.dispose();
        } else {
            System.out.println("Erro: usuarioInfo está null");
            // Aqui você pode tratar a situação, como exibir uma mensagem de erro para o usuário.
        }
    }//GEN-LAST:event_voltaPerfilActionPerformed

    private void voltaFichaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_voltaFichaActionPerformed
        InfoAcesso acesso = new InfoAcesso();
        UsuarioSession id = new UsuarioSession();
        List<String> nomesFichas = acesso.getNomesFichas(id); // Armazena o retorno do método em nomesFichas

        if (nomesFichas != null && !nomesFichas.isEmpty())
        {
            pesquisar = new TelaPesquisarFicha(nomesFichas);
            pesquisar.setVisible(true);
            pesquisar.setExtendedState(pesquisar.MAXIMIZED_BOTH);
        }
    }//GEN-LAST:event_voltaFichaActionPerformed

