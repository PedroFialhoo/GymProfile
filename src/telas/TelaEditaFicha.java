    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nomeFicha = campoEdita.getText();
    
    if (nomeFicha.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Insira o nome da ficha", "Erro", JOptionPane.ERROR_MESSAGE);
        return;
    }
    
    InfoAcesso acesso = new InfoAcesso();
    UsuarioSession id = new UsuarioSession();

    FichaInfo fichaInfo = acesso.buscarFichaEspecifica3(id, nomeFicha); 

    if (fichaInfo != null) {

        editavel = new TelaFichaEditavel(fichaInfo);
        editavel.setVisible(true);
        editavel.setExtendedState(editavel.MAXIMIZED_BOTH);
        this.dispose();

    } else {
        campoEdita.setText("Ficha não encontrada.");
    }


    }//GEN-LAST:event_jButton1ActionPerformed

